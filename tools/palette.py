#!/usr/bin/env python3
"""Generates Haven's tonal palettes (ui/theme/Palette.kt).

Every color in the app is a tone of one of the ramps below. A ramp is a
hue and a chroma in HCT, the color space Material 3 is built on, where
tone is perceptual lightness: two colors with the same tone difference
have the same contrast whatever their hue. That is what lets one rule
("container is tone 90, the ink on it is tone 10") hold for every family
instead of being re-checked pair by pair.

    pip install materialyoucolor
    python3 tools/palette.py            # rewrites Palette.kt
    python3 tools/palette.py --html     # also writes tools/palette.html

Change a hue or chroma here, run it, and the whole app follows. Do not
edit Palette.kt by hand.
"""
import sys
from pathlib import Path

from materialyoucolor.hct import Hct

# name: (hue, chroma, what it is for)
RAMPS = {
    # The scheme
    "Leaf": (140, 48, "Brand green. Primary, and the color of anything on."),
    "Sage": (140, 14, "Quiet green. Secondary."),
    "Dew": (192, 24, "Cool counterpoint. Tertiary."),
    "Cream": (118, 5, "Warm paper. Backgrounds and text."),
    "Moss": (136, 11, "Sage-tinted neutral. Containers, outlines, secondary text."),
    # State families: what the home is doing
    "Ember": (40, 52, "Heating, temperature."),
    "Frost": (255, 42, "Cooling, weather."),
    "Guard": (277, 42, "Locked, armed, secure."),
    "Alarm": (25, 70, "Open, unlocked, faults. Error."),
    "Tune": (310, 42, "Media."),
    "Volt": (90, 52, "Power and energy."),
    "Honey": (76, 62, "Motion, caution, sunlight."),
    "Rain": (237, 46, "Humidity, water."),
    "Cloud": (240, 12, "Overcast weather."),
}

TONES = [0, 4, 6, 8, 10, 12, 15, 17, 20, 22, 25, 30, 35, 40, 50, 60, 70, 80, 85, 87, 90, 92, 94, 95, 96, 98, 99, 100]

# Brand constants that are not a ramp tone: fixed in both themes.
FIXED = {
    "Lime": (0xFF9BF67C, "The brand lime: the selected capsule, the logo's doorway."),
    "Ink": (0xFF161D17, "The near-black green of the navigation bar and the logo's night field."),
    "Sun": (0xFFFFB83D, "The logo's sun."),
    "HeatSignal": (0xFFD84315, "Heating, at full strength: dial arcs and setpoints."),
    "CoolSignal": (0xFF1565C0, "Cooling, at full strength: dial arcs and setpoints."),
}


def tone(hue: float, chroma: float, t: int) -> int:
    return Hct.from_hct(hue, chroma, t).to_int() & 0xFFFFFFFF


def kotlin() -> str:
    fields = ",\n".join(f"    val t{t}: Color" for t in TONES)
    out = [
        "package com.garrietta.haven.ui.theme",
        "",
        "import androidx.compose.ui.graphics.Color",
        "",
        "/**",
        " * One hue cut at fixed tones. Tone is HCT's perceptual lightness, 0 black",
        " * to 100 white, so the same tone step gives the same contrast in every",
        " * ramp: that is what lets a rule like \"container t90, ink t10\" hold for",
        " * every family without being re-checked pair by pair.",
        " */",
        "class TonalRamp(",
        fields + ",",
        ")",
        "",
        "/**",
        " * Haven's reference palette: every color the app draws is one of these.",
        " *",
        " * GENERATED by tools/palette.py. Do not edit by hand: change a hue or a",
        " * chroma there and run it.",
        " *",
        " * Screens do not read this file. They read roles: MaterialTheme.colorScheme",
        " * for surfaces and text, and the state families in Color.kt for what the",
        " * home is doing.",
        " */",
        "object Palette {",
    ]
    for name, (hue, chroma, doc) in RAMPS.items():
        out.append(f"    /** {doc} HCT hue {hue}, chroma {chroma}. */")
        out.append(f"    val {name} = TonalRamp(")
        for t in TONES:
            out.append(f"        t{t} = Color(0x{tone(hue, chroma, t):08X}),")
        out.append("    )")
        out.append("")
    for name, (argb, doc) in FIXED.items():
        out.append(f"    /** {doc} */")
        out.append(f"    val {name} = Color(0x{argb:08X})")
        out.append("")
    out[-1] = "}"
    return "\n".join(out) + "\n"


def html() -> str:
    rows = []
    for name, (hue, chroma, doc) in RAMPS.items():
        cells = "".join(
            f'<div style="background:#{tone(hue, chroma, t) & 0xFFFFFF:06x};'
            f'color:{"#000" if t >= 50 else "#fff"}">{t}</div>'
            for t in TONES
        )
        rows.append(f"<h3>{name} <small>H{hue} C{chroma} · {doc}</small></h3><div class=r>{cells}</div>")
    return (
        "<!doctype html><meta charset=utf-8><style>body{font:13px system-ui;margin:16px;background:#fafaf5}"
        "h3{margin:10px 0 4px}small{font-weight:400;color:#555}.r{display:flex}"
        ".r div{width:44px;height:38px;display:grid;place-items:center;font-size:11px}</style>"
        + "".join(rows)
    )


if __name__ == "__main__":
    root = Path(__file__).resolve().parent.parent
    target = root / "app/src/main/java/com/garrietta/haven/ui/theme/Palette.kt"
    target.write_text(kotlin())
    print(f"wrote {target.relative_to(root)}")
    if "--html" in sys.argv:
        (root / "tools/palette.html").write_text(html())
        print("wrote tools/palette.html")
